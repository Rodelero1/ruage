"""**309 review notes, and no way to find one.** This writes `docs/reviews/INDEX.md`: one line per note.

The notes are the tree's second bank. `docs/archive/decisions-2026-11-24.md` says *what* was decided; a note says *what was measured* on the way,
and the two are useful together - D353 is half a paragraph, its note has the timings and the fixture that proved it. Nothing
readable lists them, so the only way to find "that note about the pile" is `ls | grep`, which is what a person does by hand and
an agent does badly.

**The notes are not moved.** `docs/archive/decisions-2026-11-24.md` cites them by path in a hundred places ("Review: `docs/reviews/...`"), so
archiving them into subdirectories would dangle those citations for the sake of tidiness. An index is the cheap half of the same
win.

Usage:
    python3 tools/review_index.py            # write docs/reviews/INDEX.md
    python3 tools/review_index.py --print    # print it
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REVIEWS = ROOT / "docs" / "reviews"
OUT = REVIEWS / "INDEX.md"

NAME = re.compile(r"^(20\d\d-\d\d-\d\d)-(.+)\.md$")
TITLE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
# The note's own opening claim, when it has one: the first line that is not a heading or a metadata line.
PROSE = re.compile(r"^(?!\s*$)(?!\s*[#>|*-])(.{30,})$", re.MULTILINE)


def one_line(note: Path) -> tuple[str, str, str]:
    text = note.read_text(encoding="utf-8", errors="replace")
    title = TITLE.search(text)
    heading = title.group(1).strip() if title else note.stem
    prose = PROSE.search(text[title.end() :] if title else text)
    claim = ""
    if prose:
        claim = re.sub(r"[`*_]", "", prose.group(1)).strip()
        claim = re.sub(r"\s+", " ", claim)
        if len(claim) > 160:
            claim = claim[:160].rsplit(" ", 1)[0] + " ..."
    return heading, claim, note.name


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--print", action="store_true", dest="show")
    args = parser.parse_args()

    notes: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for note in sorted(REVIEWS.glob("*.md")):
        if note.name == "INDEX.md":
            continue
        match = NAME.match(note.name)
        date = match.group(1) if match else "undated"
        heading, claim, name = one_line(note)
        notes[date].append((heading, claim, name))

    total = sum(len(rows) for rows in notes.values())
    out = [
        "<!-- Generated by tools/review_index.py. Do not edit: run `make review-index`. -->",
        "",
        "# Review notes",
        "",
        f"**{total} notes.** Newest first. Each decision row names the note that measured it; this is the other direction - what "
        "each note found, so a session can search the notes instead of listing the directory.",
        "",
        "The files are **not** moved: `docs/archive/decisions-2026-11-24.md` cites them by path, and an archive directory would dangle those "
        "citations.",
        "",
    ]
    for date in sorted(notes, reverse=True):
        out.append(f"## {date} ({len(notes[date])})")
        out.append("")
        for heading, claim, name in sorted(notes[date], key=lambda row: row[2]):
            line = f"- **{heading}** — `{name}`"
            if claim and claim.lower() not in heading.lower():
                line += f" · {claim}"
            out.append(line)
        out.append("")

    page = "\n".join(out).rstrip() + "\n"
    if args.show:
        print(page)
    else:
        OUT.write_text(page, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}: {total} notes over {len(notes)} dates, {len(page) // 1000}k characters")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
